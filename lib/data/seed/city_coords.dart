/// 需要剥离的行政区划后缀（长后缀在前，避免误剥）。
const List<String> _areaSuffixes = ['特别行政区', '自治区', '自治州', '地区', '市', '省'];

/// 剥离目的地末尾的行政区划后缀（可叠加，如「杭州市」「广西壮族自治区」）。
String stripAreaSuffix(String name) {
  var s = name.trim();
  var changed = true;
  while (changed && s.isNotEmpty) {
    changed = false;
    for (final suffix in _areaSuffixes) {
      if (s.length > suffix.length && s.endsWith(suffix)) {
        s = s.substring(0, s.length - suffix.length);
        changed = true;
      }
    }
  }
  return s;
}

/// 目的地模糊匹配内置城市坐标：
/// 第一步精确命中；第二步剥离「市/省/特别行政区/自治区/自治州/地区」后缀后精确命中；
/// 第三步用后缀剥离结果与城市名互相包含匹配（兼容「浙江省杭州市」这类复合写法）。
/// 未命中返回 null。
List<double>? matchCity(String destination) {
  final dest = destination.trim();
  if (dest.isEmpty) return null;
  if (kCityCoords.containsKey(dest)) return kCityCoords[dest];
  final stripped = stripAreaSuffix(dest);
  if (stripped.isEmpty) return null;
  if (kCityCoords.containsKey(stripped)) return kCityCoords[stripped];
  for (final entry in kCityCoords.entries) {
    final key = entry.key;
    if (key.contains(stripped) || stripped.contains(key)) return entry.value;
  }
  return null;
}