/// 从目的地字符串解析 UTC 偏移（分钟）；识别不到返回 null（调用方回退设备时区）。
///
/// 目的地可能是多城串（`东京-大阪` / `成都、稻城`），逐段尝试，取第一个命中的。
int? destinationOffsetMinutes(String destination) {
  final raw = destination.trim();
  if (raw.isEmpty) return null;
  final parts = raw
      .split(RegExp(r'[-–—~、,，/|+>→\s]+'))
      .map((s) => s.trim())
      .where((s) => s.isNotEmpty);
  for (final part in parts) {
    final lower = part.toLowerCase();
    final exact = _kOffsets[lower];
    if (exact != null) return exact;
  }
  // 第二遍：包含匹配（"东京都" / "大阪府" / "Tokyo Narita" 等）
  final lowerAll = raw.toLowerCase();
  for (final entry in _kOffsets.entries) {
    if (lowerAll.contains(entry.key)) return entry.value;
  }
  for (final entry in _kCountryOffsets.entries) {
    if (lowerAll.contains(entry.key)) return entry.value;
  }
  return null;
}

/// 偏移量 → 展示角标（`UTC+8` / `UTC+5:45` / `UTC-3`）。
String utcOffsetLabel(int offsetMinutes) {
  final sign = offsetMinutes < 0 ? '-' : '+';
  final abs = offsetMinutes.abs();
  final h = abs ~/ 60;
  final m = abs % 60;
  return m == 0 ? 'UTC$sign$h' : 'UTC$sign$h:${m.toString().padLeft(2, '0')}';
}
